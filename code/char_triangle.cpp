// 题目：给定一个字符，构造底边长 5、高 3 的等腰字符三角形
// 输入：一个字符    输出：
//   *
//  ***
// *****
#include <cstdio>                       // 【知识点 1】标准输入输出头文件
                                        // scanf / printf 都住在这里
                                        // C 语言写作 <stdio.h>，C++ 推荐 <cstdio>

int main()
{
    char c;                             // 【知识点 2】char 类型
                                        // 专门存"一个字符"，本质是存 ASCII 码的小整数
                                        // 占 1 个字节

    scanf(" %c", &c);                   // 【知识点 3】读入一个字符
                                        // 3a. %c 前面那个空格：先跳过残留的换行/空格
                                        //     不加的话可能读到上次的回车（ASCII 10）
                                        // 3b. &c：scanf 必须传"地址"，不能只写 c
                                        //     忘了 & 是初学者第一大坑

    for (int i = 1; i <= 3; i++)        // 【知识点 4】for 循环（外层）
                                        // i 从 1 到 3，表示"现在打第几行"
                                        // for(初始; 条件; 步进) 三段式
    {
        for (int j = 0; j < 3 - i; j++) // 【知识点 5】嵌套循环 + 找规律（核心考点）
            printf(" ");                // 内层循环 1：打空格
                                        // 第 i 行空格数 = 高度 - i = 3 - i
                                        //   i=1 打 2 个，i=2 打 1 个，i=3 打 0 个

        for (int j = 0; j < 2 * i - 1; j++) // 内层循环 2：打字符
            printf("%c", c);            // 第 i 行字符数 = 2 * i - 1
                                        //   i=1 打 1 个，i=2 打 3 个，i=3 打 5 个
                                        // 底边 5 = 2*3-1，题目给的数字是配套的

        printf("\n");                   // 【知识点 6】转义字符 \n
                                        // 一行的内容打完，换到下一行
                                        // 必须放在两个内层循环之后、外层循环之内
    }

    return 0;                           // 【知识点 7】返回 0 表示程序正常结束
}
